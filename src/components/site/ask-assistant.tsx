"use client";

import { CompanionPanel } from "@/components/site/companion-panel";
import type { Note } from "@/content/notes";

/**
 * "ASK ABOUT THIS ESSAY" — the shared companion panel, configured for the
 * notebook reading view. The conversation runs through /api/ask, which
 * grounds the model in the essay's actual text (the SDK never reaches
 * this file).
 */

export function AskAssistant({ note }: { note: Note }) {
  return (
    <CompanionPanel
      className="mt-10"
      endpoint="/api/ask"
      buildPayload={(question, history) => ({
        noteId: note.id,
        question,
        history,
      })}
      collapsedLabel="Ask about this essay — AI companion"
      headerLabel="Socratic companion"
      honestyNote="Answers are generated by an AI assistant reading this essay — verify anything important against the references."
      threadAriaLabel="Conversation with the essay companion"
      loadingText="Consulting the essay…"
      inputLabel="Your question about this essay"
      placeholder="Ask anything about this essay — a passage, an equation, an implication…"
      sendAriaLabel="Send your question to the essay companion"
      suggestedQuestions={[
        "Explain the central idea in simpler terms.",
        "What is the strongest objection to this argument?",
      ]}
      toastFailed="The essay companion failed to answer."
      toastUnreachable="The essay companion is unreachable."
    />
  );
}
